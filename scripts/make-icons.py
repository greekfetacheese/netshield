#!/usr/bin/env python3
"""Generate the NetShield mark: three daemon states, and every size the desktop draws.

The mark is one shield with one glyph per state:

  ok       green  + a check   daemon up, interactive mode on
  warning  amber  + a bang    daemon up, interactive mode off
  alert    red    + a bang    daemon stopped

Two things were wrong with the first version, and both are fixed here rather than in the
art: the plate was drawn at alpha 90, so every surface composited it against its own
background, and the glyph was near-black on green. The plate is now opaque and the glyph
white, and because a white glyph needs a plate dark enough to sit on, each fill is the
brightest tone of its hue that still clears 3:1 against white -- measured under the ink,
not at the fill's own mid-tone, which is why the gradient's top multiplier is 1.20.

Outputs, all regenerated by one run:

  crates/netshield-gui/assets/tray-<state>.rgba
      Raw, row-major, top-down RGBA8, exactly 64*64*4 bytes, no header, no compression.
      What the GUI embeds: the tray needs no PNG decoder, and
      `tray_icon::Icon::from_rgba` takes exactly this layout.

  crates/netshield-gui/assets/tray-<state>.png
      A 64x64 preview for humans (READMEs, file managers). Not embedded.

  packaging/icons/hicolor/<N>x<N>/apps/netshield.png
      The ok state at every size the icon theme is asked for, which is what makes a
      `.desktop` entry's `Icon=netshield` resolve instead of falling back to a generic
      glyph. Resampled from the master per size: deriving a 24 from a 32 compounds the
      softness at each hop.

``--check`` regenerates in memory and compares against the committed files, exiting
non-zero on any difference, so a stale asset fails a check instead of shipping. The RGBA
files are compared byte for byte; the PNGs are compared decoded, so a Pillow release that
writes a different but equivalent encoding is not a false alarm.

Usage:
    python3 scripts/make-icons.py           # write every file
    python3 scripts/make-icons.py --check   # verify the committed files
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "crates/netshield-gui/assets"
THEME = ROOT / "packaging/icons/hicolor"

MASTER = 1024
SS = MASTER / 64.0
EMBEDDED_SIDE = 64
THEME_SIDES = (16, 24, 32, 48, 64, 128, 256)
STATES = ("ok", "warning", "alert")

# The GUI's own ALLOWED / AMBER / ALERT_RED, deepened until a white glyph clears 3:1.
FILL = {
    "ok": (0x35, 0xA4, 0x5C),
    "warning": (0xCF, 0x7D, 0x1E),
    "alert": (0xA8, 0x1F, 0x1F),
}

# The vertical ramp, as multipliers on the fill's own luminance. The top is bounded by the
# glyph: anything brighter put the white ink below 3:1.
RAMP_TOP = 1.20
RAMP_BOTTOM = 0.72

WHITE = (0xFF, 0xFF, 0xFF)

CHECK_WIDTH = 4.2
BANG_STEM = ((32.0, 17.0), (32.0, 37.0))
BANG_STEM_WIDTH = 6.6
BANG_DOT = (32.0, 46.5, 3.6)


def _quad(p0, p1, p2, steps):
    """Sample a quadratic Bezier from p0 to p2 with control p1."""
    return [
        (
            (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t**2 * p2[0],
            (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t**2 * p2[1],
        )
        for t in (i / steps for i in range(1, steps + 1))
    ]


def _cubic(p0, p1, p2, p3, steps):
    """Sample a cubic Bezier from p0 to p3 with controls p1 and p2."""
    return [
        (
            (1 - t) ** 3 * p0[0]
            + 3 * (1 - t) ** 2 * t * p1[0]
            + 3 * (1 - t) * t**2 * p2[0]
            + t**3 * p3[0],
            (1 - t) ** 3 * p0[1]
            + 3 * (1 - t) ** 2 * t * p1[1]
            + 3 * (1 - t) * t**2 * p2[1]
            + t**3 * p3[1],
        )
        for t in (i / steps for i in range(1, steps + 1))
    ]


def _shield():
    """The shield outline in 64x64 space: rounded top, curved sides, bottom point."""
    points = [(8.0, 14.0)]
    points += _quad((8.0, 14.0), (8.0, 5.0), (16.0, 5.0), 12)  # top-left corner
    points += _quad((16.0, 5.0), (48.0, 5.0), (48.0, 5.0), 1)  # top edge
    points += _quad((48.0, 5.0), (56.0, 5.0), (56.0, 14.0), 12)  # top-right corner
    points += _cubic((56.0, 14.0), (56.0, 34.0), (48.0, 50.0), (32.0, 60.0), 40)
    points += _cubic((32.0, 60.0), (16.0, 50.0), (8.0, 34.0), (8.0, 14.0), 40)
    return points


def _scaled(points):
    return [(x * SS, y * SS) for x, y in points]


def _shade(rgb, factor):
    """Scale a colour's luminance by ``factor`` in linear space, so the hue holds."""
    out = []
    for channel in rgb:
        value = (channel / 255.0) ** 2.2 * factor
        out.append(max(0, min(255, round((value ** (1 / 2.2)) * 255))))
    return tuple(out)


def _mix(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def _gradient(top, bottom):
    """A vertical ramp filling the whole master, light at the top."""
    strip = Image.new("RGB", (1, MASTER))
    pixels = strip.load()
    for y in range(MASTER):
        pixels[0, y] = _mix(top, bottom, y / (MASTER - 1))
    return strip.resize((MASTER, MASTER), Image.Resampling.BILINEAR)


def _stroke(draw, p0, p1, width, colour):
    """A round-capped stroke: Pillow's `line` has square ends."""
    radius = width / 2.0
    draw.line(
        (p0[0] * SS, p0[1] * SS, p1[0] * SS, p1[1] * SS),
        fill=colour,
        width=round(width * SS),
    )
    for x, y in (p0, p1):
        draw.ellipse(
            (
                x * SS - radius * SS,
                y * SS - radius * SS,
                x * SS + radius * SS,
                y * SS + radius * SS,
            ),
            fill=colour,
        )


def _symbol(draw, state):
    """The white glyph: a check for `ok`, a bang for the two states that ask for attention."""
    colour = WHITE + (255,)
    if state == "ok":
        _stroke(draw, (23.0, 32.5), (29.5, 39.0), CHECK_WIDTH, colour)
        _stroke(draw, (29.5, 39.0), (41.5, 25.5), CHECK_WIDTH, colour)
        return

    _stroke(draw, BANG_STEM[0], BANG_STEM[1], BANG_STEM_WIDTH, colour)
    x, y, radius = BANG_DOT
    draw.ellipse(
        (x * SS - radius * SS, y * SS - radius * SS, x * SS + radius * SS, y * SS + radius * SS),
        fill=colour,
    )


def render(state):
    """The master for one state: 1024x1024 RGBA, plate opaque, glyph white."""
    fill = FILL[state]
    outline = _scaled(_shield())

    image = Image.new("RGBA", (MASTER, MASTER), (0, 0, 0, 0))
    plate = _gradient(_shade(fill, RAMP_TOP), _shade(fill, RAMP_BOTTOM))
    mask = Image.new("L", (MASTER, MASTER), 0)
    ImageDraw.Draw(mask).polygon(outline, fill=255)
    image.paste(plate, (0, 0), mask)

    _symbol(ImageDraw.Draw(image), state)

    # Premultiplied resize: resizing straight RGBA blends towards the black of the
    # transparent pixels and leaves a dark halo around the shield.
    return image.convert("RGBa").resize((256, 256), Image.Resampling.LANCZOS).convert("RGBA")


def resize(master, side):
    return master.convert("RGBa").resize((side, side), Image.Resampling.LANCZOS).convert("RGBA")


def rgba_path(state):
    return ASSETS / f"tray-{state}.rgba"


def preview_path(state):
    return ASSETS / f"tray-{state}.png"


def theme_path(side):
    return THEME / f"{side}x{side}/apps/netshield.png"


def outputs():
    """Every file this script owns, as (path, image) pairs, in a stable order."""
    files = []
    for state in STATES:
        master = render(state)
        embedded = resize(master, EMBEDDED_SIDE)
        files.append((rgba_path(state), embedded))
        files.append((preview_path(state), embedded))
    # The theme carries the ok state only: a menu entry's `Icon=` names one file, and
    # overwriting that name at runtime fights the icon cache.
    master = render("ok")
    for side in THEME_SIDES:
        files.append((theme_path(side), resize(master, side)))
    return files


def stale(path, image):
    """Whether ``path`` differs from ``image``; the RGBA frame is compared exactly."""
    if not path.exists():
        return "missing"
    if path.suffix == ".rgba":
        return None if path.read_bytes() == image.tobytes() else "stale"
    committed = Image.open(path).convert("RGBA")
    if committed.size != image.size or committed.tobytes() != image.tobytes():
        return "stale"
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory and fail if the committed files are stale",
    )
    args = parser.parse_args()

    files = outputs()

    if args.check:
        failures = 0
        for path, image in files:
            problem = stale(path, image)
            if problem:
                print(f"{path.relative_to(ROOT)} is {problem}", file=sys.stderr)
                failures += 1
        if failures:
            print("run: python3 scripts/make-icons.py", file=sys.stderr)
            return 1
        print(f"{len(files)} icon file(s) are up to date")
        return 0

    for path, image in files:
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.suffix == ".rgba":
            raw = image.tobytes()
            expected = EMBEDDED_SIDE * EMBEDDED_SIDE * 4
            if len(raw) != expected:
                raise SystemExit(f"generated {len(raw)} bytes for {path}, expected {expected}")
            path.write_bytes(raw)
        else:
            image.save(path)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
